import test from 'node:test';
import assert from 'node:assert/strict';
import { translate, finalSql, scalarMinMax, groupConcat } from './translate.mjs';

const schema = {
  cols: (t) => ({ stats_hourly: ['hour', 'metric', 'value'], app_config: ['cfg_key', 'cfg_value'], favorites_db: ['user_id', 'anime_id', 'season_id', 'created_at'] }[t] || []),
  pk: (t) => ({ stats_hourly: ['hour', 'metric'], app_config: ['cfg_key'] }[t] || []),
};
const T = (s) => finalSql(translate(s, schema)).replace(/\s+/g, ' ').trim();

test('placeholders are numbered and string literals are untouched', () => {
  assert.equal(T("SELECT * FROM t WHERE a=? AND b='x?y' AND c=?"), "SELECT * FROM t WHERE a=$1 AND b='x?y' AND c=$2");
});
test('DDL: INTEGER -> BIGINT, identity, WITHOUT ROWID', () => {
  const s = T('CREATE TABLE IF NOT EXISTS anime_db (id INTEGER PRIMARY KEY, name TEXT, created_at INTEGER DEFAULT 0)');
  assert.match(s, /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/); assert.match(s, /created_at BIGINT DEFAULT 0/);
  assert.match(T('CREATE TABLE x (a INTEGER, b REAL, PRIMARY KEY (a)) WITHOUT ROWID'), /^CREATE TABLE x \(a BIGINT, b DOUBLE PRECISION, PRIMARY KEY \(a\)\)$/);
  assert.match(T('CREATE TABLE y (id INTEGER PRIMARY KEY AUTOINCREMENT, n TEXT)'), /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(T('ALTER TABLE epizod_db ADD COLUMN ready_at INTEGER DEFAULT 0'), /ADD COLUMN ready_at BIGINT DEFAULT 0/);
});
test('comments inside DDL are dropped', () => {
  assert.doesNotMatch(T("CREATE TABLE z ( -- izoh ?\n a INTEGER /* x */ )"), /izoh|\/\*/);
});
test('scalar MAX/MIN -> GREATEST/LEAST, aggregate MAX unchanged, nested', () => {
  assert.equal(scalarMinMax('MAX(COALESCE(a,0), COALESCE((SELECT MAX(MAX(x,y)) FROM t),0))'), 'GREATEST(COALESCE(a,0), COALESCE((SELECT MAX(GREATEST(x,y)) FROM t),0))');
  assert.equal(scalarMinMax('SELECT MAX(epizod_id) FROM e'), 'SELECT MAX(epizod_id) FROM e');
  assert.equal(scalarMinMax('MIN(a,b)'), 'LEAST(a,b)');
});
test('INSERT OR IGNORE -> ON CONFLICT DO NOTHING (before RETURNING)', () => {
  assert.equal(T('INSERT OR IGNORE INTO app_config (cfg_key,cfg_value) VALUES (?,?)'), 'INSERT INTO app_config (cfg_key,cfg_value) VALUES ($1,$2) ON CONFLICT DO NOTHING');
  assert.match(T('INSERT OR IGNORE INTO t (a) VALUES (?) RETURNING *'), /ON CONFLICT DO NOTHING RETURNING \*$/);
});
test('REPLACE INTO -> upsert with EXCLUDED', () => {
  assert.equal(T('REPLACE INTO app_config (cfg_key,cfg_value) VALUES (?,?)'), 'INSERT INTO app_config (cfg_key,cfg_value) VALUES ($1,$2) ON CONFLICT (cfg_key) DO UPDATE SET cfg_value=EXCLUDED.cfg_value');
});
test('ON CONFLICT DO UPDATE: bare columns get the table name (ambiguity in Postgres)', () => {
  const s = T('INSERT INTO stats_hourly (hour,metric,value) VALUES (?,?,?) ON CONFLICT(hour,metric) DO UPDATE SET value=value+excluded.value');
  assert.match(s, /DO UPDATE SET value=stats_hourly\.value\+excluded\.value/);
  assert.match(T("INSERT INTO app_config (cfg_key,cfg_value) VALUES (?,?) ON CONFLICT(cfg_key) DO UPDATE SET cfg_value=excluded.cfg_value"), /cfg_value=excluded\.cfg_value/);
});
test('LIKE -> ILIKE, GROUP_CONCAT -> string_agg', () => {
  assert.match(T('SELECT * FROM t WHERE name LIKE ?'), /ILIKE \$1/);
  assert.equal(T("SELECT GROUP_CONCAT(name, ', ') FROM t"), "SELECT string_agg((name)::text, ', ') FROM t");
  assert.equal(groupConcat('GROUP_CONCAT(x)'), "string_agg((x)::text, ',')");
});
test('UPDATE ... RETURNING and DELETE keep shape', () => {
  assert.equal(T('UPDATE epizod_db SET ready_at=? WHERE anime_id=? RETURNING *'), 'UPDATE epizod_db SET ready_at=$1 WHERE anime_id=$2 RETURNING *');
  assert.equal(T('DELETE FROM users_db WHERE id=?'), 'DELETE FROM users_db WHERE id=$1');
});
