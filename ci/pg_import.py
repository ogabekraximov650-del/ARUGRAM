#!/usr/bin/env python3
"""SQLite JSONL dump (ample-rs `RECOVER_OUT`) -> Supabase Postgres, sxema `aru` (PostgREST'ga ochiq EMAS).
UZ: jadvallar `*.schema.sql` dan Postgres turlariga o'tkaziladi, qatorlar `*.jsonl` dan yoziladi, hisob solishtiriladi.
EN: converts SQLite DDL, loads rows, verifies counts. Env: DUMP_DIR, PG_JSON (ref,user,password,db,region)."""
import json, os, re, sys, glob
import psycopg2
from psycopg2.extras import execute_values

D = os.environ["DUMP_DIR"]
cfg = json.loads(os.environ["PG_JSON"])
ref, region = cfg["ref"], cfg.get("region", "ap-northeast-1")
cands = [
    (f"aws-0-{region}.pooler.supabase.com", 5432, f"{cfg['user']}.{ref}"),
    (f"aws-1-{region}.pooler.supabase.com", 5432, f"{cfg['user']}.{ref}"),
    (f"db.{ref}.supabase.co", 5432, cfg["user"]),
]
conn = None
for h, p, u in cands:
    try:
        conn = psycopg2.connect(host=h, port=p, user=u, password=cfg["password"], dbname=cfg["db"], connect_timeout=15, sslmode="require")
        print("ulandi:", h)
        break
    except Exception as e:
        print("ulanmadi:", h, str(e)[:120].replace(cfg["password"], "***"))
if not conn:
    sys.exit("Supabase'ga ulanib bo'lmadi")
conn.autocommit = False
cur = conn.cursor()
cur.execute("set search_path to aru")

q = lambda n: '"' + n.replace('"', '""') + '"'

def split_top(s):
    out, depth, cur_, inq = [], 0, "", None
    for ch in s:
        if inq:
            cur_ += ch
            if ch == inq: inq = None
            continue
        if ch in "'\"`": inq = ch; cur_ += ch; continue
        if ch == "(": depth += 1
        if ch == ")": depth -= 1
        if ch == "," and depth == 0: out.append(cur_.strip()); cur_ = ""; continue
        cur_ += ch
    if cur_.strip(): out.append(cur_.strip())
    return out

def ident(tok):
    return tok.strip().strip('"`[]')

def conv_type(t):
    u = t.upper()
    if "INT" in u: return "BIGINT"
    if any(x in u for x in ("REAL", "FLOA", "DOUB")): return "DOUBLE PRECISION"
    if "BLOB" in u: return "BYTEA"
    if any(x in u for x in ("CHAR", "CLOB", "TEXT")) or u == "": return "TEXT"
    return "TEXT"  # NUMERIC va boshqalar — xavfsiz tomon

def convert(name, sql):
    m = re.search(r"\((.*)\)\s*(WITHOUT ROWID)?\s*;?\s*$", sql, re.S | re.I)
    body = m.group(1)
    cols, items, pk_cols = [], [], []
    for it in split_top(body):
        head = it.split(None, 1)[0].upper().strip('"`[]')
        if head in ("PRIMARY", "UNIQUE", "FOREIGN", "CHECK", "CONSTRAINT"):
            if head == "PRIMARY":
                pk = re.search(r"\((.*)\)", it, re.S).group(1)
                items.append("PRIMARY KEY (" + ", ".join(q(ident(c)) for c in pk.split(",")) + ")")
            elif head == "UNIQUE":
                uq = re.search(r"\((.*)\)", it, re.S).group(1)
                items.append("UNIQUE (" + ", ".join(q(ident(c)) for c in uq.split(",")) + ")")
            continue
        parts = it.split(None, 2)
        cname = ident(parts[0])
        rest = it[len(parts[0]):].strip()
        tm = re.match(r"([A-Za-z]+(?:\s*\(\s*\d+(?:\s*,\s*\d+)?\s*\))?)", rest)
        ctype = tm.group(1) if tm else ""
        rest2 = rest[len(ctype):]
        auto = bool(re.search(r"AUTOINCREMENT", rest2, re.I))
        ispk = bool(re.search(r"PRIMARY\s+KEY", rest2, re.I))
        pgt = conv_type(ctype)
        line = q(cname) + " "
        if ispk and pgt == "BIGINT" and (auto or ctype.upper() in ("INTEGER", "INT")):
            line += "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        else:
            line += pgt
            if ispk: line += " PRIMARY KEY"
            if re.search(r"NOT\s+NULL", rest2, re.I): line += " NOT NULL"
            if re.search(r"\bUNIQUE\b", rest2, re.I): line += " UNIQUE"
            d = re.search(r"DEFAULT\s+('(?:[^']|'')*'|-?\d+(?:\.\d+)?|\([^)]*\)|[A-Za-z_]+)", rest2, re.I)
            if d:
                dv = d.group(1)
                if dv.startswith("(") and re.search(r"strftime|unixepoch|datetime", dv, re.I): dv = None
                if dv and pgt in ("BIGINT", "DOUBLE PRECISION") and dv.startswith("'"): dv = dv.strip("'") or None
                if dv and dv.upper() == "NULL": dv = None
                if dv: line += f" DEFAULT {dv}"
        cols.append((cname, pgt))
        items.append(line)
    return cols, f"CREATE TABLE {q(name)} (\n  " + ",\n  ".join(items) + "\n)"

tables = sorted(os.path.basename(f)[:-11] for f in glob.glob(D + "/*.schema.sql"))
print("jadvallar:", len(tables))
cur.execute("select tablename from pg_tables where schemaname='aru'")
for (t,) in cur.fetchall():
    cur.execute(f"drop table if exists aru.{q(t)} cascade")
meta = {}
for t in tables:
    sql = open(f"{D}/{t}.schema.sql").read()
    cols, ddl = convert(t, sql)
    try:
        cur.execute(ddl)
    except Exception as e:
        conn.rollback(); cur = conn.cursor(); cur.execute("set search_path to aru")
        sys.exit(f"DDL xato ({t}): {str(e)[:300]}\n{ddl[:600]}")
    meta[t] = cols
conn.commit()

def val(v, pgt):
    if isinstance(v, dict) and "$hex" in v: return psycopg2.Binary(bytes.fromhex(v["$hex"]))
    if pgt == "BYTEA" and isinstance(v, str): return psycopg2.Binary(v.encode())
    return v

bad = 0
for t in tables:
    rows = [json.loads(l) for l in open(f"{D}/{t}.jsonl") if l.strip()]
    cols = meta[t]
    if not rows:
        print(f"  {t}: 0"); continue
    # tur mos kelmasa (SQLite erkin) ustun TEXT ga o'tadi
    for c, pgt in cols:
        if pgt in ("BIGINT", "DOUBLE PRECISION"):
            if any(isinstance(r.get(c), str) or isinstance(r.get(c), dict) for r in rows):
                cur.execute(f"alter table {q(t)} alter column {q(c)} drop identity if exists")
                cur.execute(f"alter table {q(t)} alter column {q(c)} type text using {q(c)}::text")
                print(f"  ! {t}.{c} -> TEXT (aralash qiymatlar)")
    cur.execute("select column_name, data_type from information_schema.columns where table_schema='aru' and table_name=%s", (t,))
    actual = dict(cur.fetchall())
    names = [c for c, _ in cols]
    data = []
    for r in rows:
        row = []
        for c in names:
            v = r.get(c)
            if actual.get(c) == "text" and isinstance(v, (int, float)) and not isinstance(v, bool): v = str(v)
            row.append(val(v, dict(cols)[c]))
        data.append(tuple(row))
    execute_values(cur, f"insert into {q(t)} ({', '.join(q(c) for c in names)}) overriding system value values %s", data, page_size=200)
    cur.execute(f"select count(*) from {q(t)}")
    n = cur.fetchone()[0]
    ok = "OK" if n == len(rows) else "MOS EMAS"
    if n != len(rows): bad += 1
    print(f"  {t}: {n}/{len(rows)} {ok}")
# identity hisoblagichlari
cur.execute("select table_name, column_name from information_schema.columns where table_schema='aru' and is_identity='YES'")
for t, c in cur.fetchall():
    cur.execute(f"select setval(pg_get_serial_sequence('aru.{q(t)}', %s), coalesce((select max({q(c)}) from {q(t)}), 0) + 1, false)", (c,))
conn.commit()
# RLS: PostgREST sxemasi emas, lekin ehtiyot uchun
for t in tables:
    cur.execute(f"alter table {q(t)} enable row level security")
conn.commit()
print("TAYYOR" if not bad else f"MOS KELMAGAN JADVALLAR: {bad}")
sys.exit(1 if bad else 0)
